/** Darf dieser Anhang weitergeleitet bzw. heruntergeladen werden (rein)? Endung und Typ, auch Doppelendungen. */
export function anhangErlaubt(name: string | null | undefined, contentType: string | null | undefined): boolean {
  const n = (name ?? "").trim().toLowerCase().replace(/[\s.]+$/, "");
  const teile = n.split(".").slice(1);
  if (teile.some((e) => GESPERRT_ENDUNG.has(e))) return false;
  if (GESPERRT_TYP.test(contentType ?? "")) return false;
  return true;
}

/** Text aus HTML (rein, einfach): Absätze und Umbrüche bleiben, Tags und Stile fallen weg. */
export function htmlZuText(html: string): string {
  return html
    .replace(/<(style|script|head)[^>]*>[\s\S]*?<\/\1>/gi, "")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<\/(p|div|li|tr|h[1-6]|blockquote)>/gi, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const ZITAT = [/^\s*(am|on)\s.+\s(schrieb|wrote)\b.*:?\s*$/i, /^\s*-{2,}\s*(ursprüngliche nachricht|original message)/i, /^\s*(von|from):\s.+$/i, /^\s*>/];

/** Antwort ohne zitierte frühere Mail (rein) für den Verlauf; bleibt nichts übrig, der ganze Text. */
export function ohneZitat(text: string): string {
  const zeilen = text.replace(/\r\n/g, "\n").split("\n");
  const i = zeilen.findIndex((z) => ZITAT.some((r) => r.test(z)));
  const kurz = (i >= 0 ? zeilen.slice(0, i) : zeilen).join("\n").trim();
  return kurz || text.trim();
}

/** Betreff ohne „AW:“, „Re:“, „WG:“ am Anfang (rein). */
export function betreffKern(subject: string): string {
  return (subject ?? "").replace(/^\s*((re|aw|wg|fw|fwd|antw)\s*(\[\d+\])?\s*:\s*)+/i, "").trim();
}

const esc = (v: string) => v.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const anzeige = (v: string) => v.replace(/["<>\\\r\n|]/g, " ").replace(/\s+/g, " ").trim().slice(0, 60);

export type WeiterleitungInhalt = { fromName: string; subject: string; text: string; html: string };

/**
 * Weiterleitung an den Vermittler (rein, Sie-Form, ohne Gedankenstriche): Kopfzeilen, Hinweise, Link in die App, dann die
 * Nachricht. `htmlOriginal` nur, wenn klein genug; sonst der Text.
 */
export function weiterleitungInhalt(o: {
  leadName: string | null;
  leadAdresse: string;
  subject: string;
  text: string;
  htmlOriginal?: string | null;
  appLink?: string | null;
  hinweise?: string[];
  zugeordnet: boolean;
}): WeiterleitungInhalt {
  const name = anzeige(o.leadName || "") || o.leadAdresse;
  const kern = betreffKern(o.subject) || "(ohne Betreff)";
  const kopf = o.zugeordnet
    ? `${name} hat auf Ihre E-Mail geantwortet. Antworten Sie einfach auf diese E-Mail, sie geht direkt an ${o.leadAdresse}.`
    : `Diese E-Mail kam an Ihre Antwortadresse, der Absender ${o.leadAdresse} ist keinem Kontakt zugeordnet. Antworten Sie nur, wenn Sie den Absender kennen.`;
  const zeilen = [kopf, ...(o.hinweise ?? []), ...(o.appLink ? [`Kontakt in der App: ${o.appLink}`] : [])];
  const text = `${zeilen.join("\n")}\n\nNachricht:\n\n${o.text}`;
  const kopfHtml = `<div style="margin:0 0 16px;padding:12px 14px;border-radius:8px;background:#f1f5f9;font-size:13px;line-height:1.5;color:#334155">${zeilen
    .map((z, i) => (i === 0 ? `<strong>${esc(z)}</strong>` : esc(z).replace(/(https?:\/\/\S+)/g, '<a href="$1" style="color:#2563eb">$1</a>')))
    .join("<br>")}</div>`;
  const inhalt = o.htmlOriginal && o.htmlOriginal.length <= 2_000_000 ? o.htmlOriginal : `<div style="white-space:pre-wrap;font-size:14px;line-height:1.5">${esc(o.text)}</div>`;
  return {
    fromName: `${name} (Antwort)`,
    subject: `Antwort von ${name}: ${kern}`.slice(0, 250),
    text,
    html: `${kopfHtml}${inhalt}`,
  };
}

/** Anhänge aufteilen (rein): weiterleiten (erlaubt, nicht eingebettet, zusammen ≤ Limit), gesperrt, zu groß. */
export function anhaengeWaehlen(liste: Pick<EmpfangenerAnhang, "id" | "filename" | "size" | "contentType" | "inline">[], limit = ANHANG_LIMIT) {
  const erlaubt = liste.filter((a) => anhangErlaubt(a.filename, a.contentType));
  const gesperrt = liste.filter((a) => !anhangErlaubt(a.filename, a.contentType));
  const dateien = erlaubt.filter((a) => !a.inline);
  const summe = dateien.reduce((s, a) => s + a.size, 0);
  return { weiterleiten: summe <= limit ? dateien : [], zuGross: summe > limit ? dateien : [], gesperrt, summe };
}

