/**
 * Ereignis „email.received“ verarbeiten. Wirft nur bei Fehlern, die eine Wiederholung lösen kann (API, Versand): dann
 * antwortet der Webhook mit 500 und Resend versucht es erneut; der Fortschritt bleibt erhalten.
 */
export async function verarbeiteMailEingang(event: EmailReceivedEvent, o: { now?: Date; api?: EingangApi } = {}): Promise<EingangErgebnis> {
  const now = o.now ?? new Date();
  const emailId = event.data?.email_id;
  if (!emailId) return { ergebnis: "ignoriert", grund: "ohne_id" };
  const empfaenger = [...(event.data?.to ?? []), ...(event.data?.cc ?? []), ...(event.data?.bcc ?? []), ...(event.data?.received_for ?? [])];
  const ziel = empfaenger.map((a) => parseAntwortAdresse(a)).find((x) => !!x) ?? null;

  const zeile = await reserviere(emailId, now);
  if (!zeile) return { ergebnis: "doppelt" };
  const id = zeile.id;
  if (!ziel) {
    await abschliessen(id, { ergebnis: "ignoriert", grund: "fremde_adresse" });
    return { ergebnis: "ignoriert", grund: "fremde_adresse", eingangId: id };
  }
  const schalter = antwortEingangAn();
  const apiKey = process.env.RESEND_API_KEY?.trim();
  if (!apiKey) {
    await abschliessen(id, { ergebnis: "fehler", grund: "kein_schluessel" });
    return { ergebnis: "fehler", grund: "kein_schluessel", eingangId: id };
  }

  try {
    // 1. Zuordnung: Leadcode, sonst Absender beim Kunden des Kurznamens, sonst nur der Kunde
    let lead: { id: string; customerId: string; name: string | null; email: string | null } | null = null;
    let zuordnung: "code" | "absender" | "kunde" | "keine" = "keine";
    if (ziel.code) {
      lead = await prisma.lead.findFirst({ where: { antwortCode: ziel.code, erasedAt: null }, select: { id: true, customerId: true, name: true, email: true } });
      if (lead) zuordnung = "code";
    }
    if (!lead && !schalter) {
      await abschliessen(id, { ergebnis: "ignoriert", grund: "schalter_aus" });
      return { ergebnis: "ignoriert", grund: "schalter_aus", eingangId: id };
    }

    const api = o.api ?? (await ladeApi(apiKey));
    const mail = await api.mail(emailId);
    const from = reineAdresse(mail.from) ?? reineAdresse(event.data?.from) ?? null;
    if (istSchleife(from, mail.headers)) {
      await abschliessen(id, { ergebnis: "ignoriert", grund: "schleife", customerId: lead?.customerId ?? null });
      return { ergebnis: "ignoriert", grund: "schleife", eingangId: id };
    }

    let customerId = lead?.customerId ?? null;
    if (!lead && ziel.kurz) {
      const cal = await prisma.calendarConnection.findFirst({
        where: { OR: [{ bookingSlug: { equals: ziel.kurz, mode: "insensitive" } }, { bookingSlugAlt: { has: ziel.kurz } }] },
        select: { customerId: true },
      });
      customerId = cal?.customerId ?? null;
      if (customerId && from) {
        lead = await prisma.lead.findFirst({
          where: { customerId, erasedAt: null, OR: [{ email: { equals: from, mode: "insensitive" } }, { weitereEmails: { has: from } }] },
          orderBy: { createdAt: "desc" },
          select: { id: true, customerId: true, name: true, email: true },
        });
        zuordnung = lead ? "absender" : "kunde";
      }
    }
    if (!customerId || !from) {
      await abschliessen(id, { ergebnis: "ignoriert", grund: from ? "unbekannt" : "ohne_absender" });
      return { ergebnis: "ignoriert", grund: from ? "unbekannt" : "ohne_absender", eingangId: id };
    }
    const kunde = await prisma.customer.findUnique({ where: { id: customerId }, select: { dataDeletedAt: true } });
    if (!kunde || kunde.dataDeletedAt) {
      await abschliessen(id, { ergebnis: "ignoriert", grund: "kunde_geloescht", customerId: null });
      return { ergebnis: "ignoriert", grund: "kunde_geloescht", eingangId: id };
    }

    // 2. Prüfen: automatische Antwort, Absender bestätigt
    const auto = autoAntwortGrund(mail.headers, mail.subject, from);
    const unbestaetigt = !auto && authFehler(mail.authentication, mail.headers);
    const text = (mail.text?.trim() || (mail.html ? htmlZuText(mail.html) : "")).slice(0, 200_000);
    const anhaengeListe = await api.anhaenge(emailId);
    const wahl = anhaengeWaehlen(anhaengeListe);
    const weiter = new Set(wahl.weiterleiten.map((a) => a.id));
    const anhaengeMeta = anhaengeListe
      .filter((a) => !a.inline || !anhangErlaubt(a.filename, a.contentType))
      .map((a) => ({ id: a.id, name: (a.filename ?? "Anhang").slice(0, 160), groesse: a.size, typ: a.contentType.slice(0, 100), erlaubt: anhangErlaubt(a.filename, a.contentType), weitergeleitet: weiter.has(a.id) }));

    // 3. Nur Kunde: Weiterleitung mit Hinweis, ohne Anhänge, ohne Verlauf
    if (!lead) {
      if (auto || unbestaetigt) {
        await abschliessen(id, { ergebnis: "ignoriert", grund: auto ? `auto_${auto}` : "absender_unbestaetigt", customerId, zuordnung });
        return { ergebnis: "ignoriert", grund: auto ? "auto_antwort" : "absender_unbestaetigt", eingangId: id };
      }
      const heute = await prisma.mailEingang.count({ where: { customerId, zuordnung: "kunde", weitergeleitetAt: { gt: new Date(now.getTime() - 86_400_000) } } });
      if (heute >= KUNDE_LIMIT_TAG) {
        await abschliessen(id, { ergebnis: "ignoriert", grund: "limit", customerId, zuordnung });
        return { ergebnis: "ignoriert", grund: "limit", eingangId: id };
      }
      if (!zeile.weitergeleitetAt) {
        const hinweise = anhaengeMeta.length ? [`Anhänge wurden nicht weitergeleitet (${anhaengeMeta.length}), weil der Absender unbekannt ist.`] : [];
        await weiterleiten(apiKey, { customerId, leadId: null, leadName: null, from, subject: mail.subject, text, html: mail.html, hinweise, zugeordnet: false, eingangId: id, anhaenge: [], api });
        await prisma.mailEingang.update({ where: { id }, data: { weitergeleitetAt: now } });
      }
      await abschliessen(id, { ergebnis: "hinweis", grund: "kunde", customerId, zuordnung });
      return { ergebnis: "hinweis", grund: "kunde", eingangId: id };
    }

    // 4. Lead: Verlauf, Weiterleitung, Push
    const L = lead;
    const art: MailArt = auto ? "antwort_auto" : unbestaetigt ? "antwort_ungeprueft" : "antwort";
    const reason = auto
      ? "Automatische Antwort (z. B. Abwesenheitsnotiz), zählt nicht als Antwort."
      : unbestaetigt
        ? "Absender nicht bestätigt (SPF/DKIM/DMARC). Nicht weitergeleitet, zählt nicht als Antwort."
        : null;
    if (!zeile.contactMailId) {
      const subject = (mail.subject || "(ohne Betreff)").slice(0, 500);
      await prisma.$transaction(async (tx) => {
        const cm = await tx.contactMail.create({
          data: {
            customerId: L.customerId,
            leadId: L.id,
            kind: art,
            automatic: false,
            richtung: "eingang",
            recipient: from.slice(0, 320),
            subject,
            body: ohneZitat(text).slice(0, 20_000),
            status: "empfangen",
            reason,
            statusAt: now,
            provider: "resend",
            providerMessageId: null,
            createdAt: now,
          },
          select: { id: true },
        });
        await tx.leadHistory.create({
          data: {
            leadId: L.id,
            customerId: L.customerId,
            kind: "email",
            text: mailVerlaufText({ art, automatic: false, to: from, subject, status: "empfangen", richtung: "eingang" }).slice(0, 4000),
            mailId: cm.id,
            createdAt: now,
          },
        });
        await tx.mailEingang.update({ where: { id }, data: { contactMailId: cm.id, leadId: L.id, customerId: L.customerId, zuordnung, anhaenge: anhaengeMeta } });
      });
    }
    if (art !== "antwort") {
      await abschliessen(id, { ergebnis: "hinweis", grund: auto ? `auto_${auto}` : "absender_unbestaetigt", customerId: lead.customerId, leadId: lead.id, zuordnung });
      return { ergebnis: "hinweis", grund: auto ? "auto_antwort" : "absender_unbestaetigt", eingangId: id };
    }

    // Betroffenenrechte (Ole, 18.11.2026, lib/dsgvo): Anfrage ohne KI erkennen, Eingang bestätigen, Widerspruch sofort
    // umsetzen. Die Mail geht wie jede Antwort an den Vermittler weiter. Je Eingang höchstens einmal (quelleId).
    await import("@/lib/dsgvo/server")
      .then((m) => m.pruefeDsgvoEingang({ customerId: lead.customerId, leadId: lead.id, kanal: "email", text: ohneZitat(text), betreff: betreffKern(mail.subject), quelleId: id, absender: from, now }))
      .catch(() => console.error("[mail-eingang] Datenschutz-Prüfung fehlgeschlagen"));

    if (!zeile.weitergeleitetAt) {
      const link = await appLink(lead.id);
      const hinweise: string[] = [];
      if (wahl.zuGross.length) hinweise.push(`Die Anhänge (${wahl.zuGross.length}, zusammen ${mb(wahl.summe)}) sind zu groß zum Weiterleiten. Sie finden sie beim Kontakt in der App.`);
      if (wahl.gesperrt.length) hinweise.push(`Aus Sicherheitsgründen nicht weitergeleitet: ${wahl.gesperrt.map((a) => a.filename ?? "Anhang").join(", ").slice(0, 300)}.`);
      await weiterleiten(apiKey, { customerId: lead.customerId, leadId: lead.id, leadName: lead.name, from, subject: mail.subject, text, html: mail.html, hinweise, zugeordnet: true, eingangId: id, anhaenge: wahl.weiterleiten, api, link });
      await prisma.mailEingang.update({ where: { id }, data: { weitergeleitetAt: now } });
    }
    if (!zeile.pushAt) {
      await pushAnVermittler(lead, now);
      await prisma.mailEingang.update({ where: { id }, data: { pushAt: now } });
    }
    await abschliessen(id, { ergebnis: "antwort", grund: null, customerId: lead.customerId, leadId: lead.id, zuordnung });
    return { ergebnis: "antwort", eingangId: id };
  } catch (err) {
    const grund = err instanceof Error ? err.message.replace(/[^\w:.-]/g, "_").slice(0, 80) : "fehler";
    await prisma.mailEingang.update({ where: { id }, data: { ergebnis: "fehler", grund } }).catch(() => null);
    console.error("[mail-eingang] Fehler", grund);
    throw new Error(`mail_eingang:${grund}`);
  }
}

async function weiterleiten(
  apiKey: string,
  o: {
    customerId: string;
    leadId: string | null;
    leadName: string | null;
    from: string;
    subject: string;
    text: string;
    html: string | null;
    hinweise: string[];
    zugeordnet: boolean;
    eingangId: string;
    anhaenge: Pick<EmpfangenerAnhang, "id" | "filename" | "size" | "contentType">[];
    api: EingangApi;
    link?: string | null;
  },
): Promise<void> {
  const absender = leadMailAdresse();
  if (!absender) throw new Error("kein_absender");
  const ziel = await weiterleitungsZiel(o.customerId, o.leadId);
  if (!ziel) {
    console.error("[mail-eingang] kein Ziel für die Weiterleitung");
    return;
  }
  const w = weiterleitungInhalt({ leadName: o.leadName, leadAdresse: o.from, subject: o.subject, text: o.text, htmlOriginal: o.html, appLink: o.link ?? null, hinweise: o.hinweise, zugeordnet: o.zugeordnet });
  // Download-Adressen gelten 1 h: frisch aus der Liste (bei einer Wiederholung neu geladen)
  const frisch = o.anhaenge.length ? await o.api.anhaenge((await prisma.mailEingang.findUnique({ where: { id: o.eingangId }, select: { resendEmailId: true } }))!.resendEmailId) : [];
  const attachments: { filename: string; content: Buffer; contentType: string }[] = [];
  for (const a of o.anhaenge) {
    const f = frisch.find((x) => x.id === a.id);
    if (!f?.downloadUrl) throw new Error("anhang_ohne_adresse");
    attachments.push({ filename: (a.filename ?? "anhang").replace(/[\\/\r\n"]/g, "_").slice(0, 160), content: await o.api.datei(f.downloadUrl, ANHANG_LIMIT), contentType: a.contentType });
  }
  const { mailClient, wasBlocked } = await import("@/lib/mail-guard");
  const res = await mailClient(apiKey).emails.send({
    from: `"${w.fromName}" <${absender}>`,
    to: ziel.email,
    replyTo: o.from,
    subject: w.subject,
    text: w.text,
    html: w.html,
    headers: { [EINGANG_KOPF]: o.eingangId },
    ...(attachments.length ? { attachments } : {}),
  });
  if (wasBlocked(res)) return;
  if (res.error) throw new Error(`weiterleitung:${res.error.name ?? "fehler"}`);
}

async function pushAnVermittler(lead: { id: string; customerId: string; name: string | null }, now: Date): Promise<void> {
  try {
    const l = await prisma.lead.findUnique({ where: { id: lead.id }, select: { assignedUserId: true, assignedUser: { select: { customerId: true } } } });
    const { sendToBuyersOfCustomer, sendToUser } = await import("@/lib/push");
    const name = anzeige(lead.name ?? "") || "einem Kontakt";
    // Neutral: kein Inhalt (Gesundheitsangaben möglich), nur dass eine Antwort da ist
    const payload = { title: `Neue Antwort von ${name}`, body: "Per E-Mail. Die Nachricht steht im Kontaktverlauf.", url: `/buyer/leads/${lead.id}`, tag: `mail-antwort:${lead.id}:${now.getTime()}` };
    const zustaendig = l?.assignedUserId && l.assignedUser?.customerId === lead.customerId ? l.assignedUserId : null;
    await (zustaendig ? sendToUser(zustaendig, payload) : sendToBuyersOfCustomer(lead.customerId, payload));
  } catch {
    console.error("[mail-eingang] Push fehlgeschlagen");
  }
}
