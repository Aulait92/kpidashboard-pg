const AUTO_BETREFF =
  /^\s*(automatische antwort|automatic reply|auto(matic)?[ -]?reply|autoreply|abwesenheitsnotiz|abwesenheit|out of (the )?office|ich bin (nicht im büro|abwesend)|undeliverable|unzustellbar|nicht zustellbar|delivery status notification|mail delivery (failed|subsystem)|returned mail)/i;
const AUTO_ABSENDER = /^(mailer-daemon|postmaster|no-?reply|do-?not-?reply|bounces?|auto-?reply)([+@.-]|$)/i;

/**
 * Automatisch erzeugte Mail (rein)? Grund oder null. Auto-Submitted (außer „no“), Precedence bulk/junk/list/auto_reply,
 * X-Autoreply/X-Autorespond, Listen (List-Id, List-Unsubscribe), Zustellberichte, typische Absender und Betreffzeilen.
 */
export function autoAntwortGrund(headers: Record<string, string> | null | undefined, subject: string, from: string | null): string | null {
  const h: Record<string, string> = {};
  for (const [k, v] of Object.entries(headers ?? {})) h[k.toLowerCase()] = String(v ?? "").toLowerCase();
  const as = (h["auto-submitted"] ?? "").trim();
  if (as && !as.startsWith("no")) return "auto_submitted";
  if (/\b(bulk|junk|list|auto_reply)\b/.test(h["precedence"] ?? "")) return "precedence";
  if (h["x-autoreply"] || h["x-autorespond"] || h["x-autogenerated"] || h["x-auto-reply"]) return "auto_kopf";
  if (h["list-id"] || h["list-unsubscribe"]) return "liste";
  if (/multipart\/report/.test(h["content-type"] ?? "")) return "zustellbericht";
  if (from && AUTO_ABSENDER.test(from.split("@")[0] ?? "")) return "absender";
  if (AUTO_BETREFF.test(subject ?? "")) return "betreff";
  return null;
}

/**
 * Absender nicht bestätigt (rein): DMARC „fail“ oder SPF und DKIM beide „fail“. Ohne Angabe (null) bzw. „gray“,
 * „unknown“: bestätigt genug (viele kleine Domains haben kein DMARC). Fällt zurück auf Authentication-Results.
 */
export function authFehler(a: AuthErgebnis, headers?: Record<string, string> | null): boolean {
  const norm = (v: string | null | undefined) => (v ?? "").toLowerCase().trim();
  let spf = norm(a?.spf);
  let dkim = norm(a?.dkim);
  let dmarc = norm(a?.dmarc);
  if (!a) {
    const ar = norm(headers?.["authentication-results"]);
    spf = /\bspf=(\w+)/.exec(ar)?.[1] ?? "";
    dkim = /\bdkim=(\w+)/.exec(ar)?.[1] ?? "";
    dmarc = /\bdmarc=(\w+)/.exec(ar)?.[1] ?? "";
  }
  if (dmarc === "fail") return true;
  return spf === "fail" && dkim === "fail";
}

/** Eigene Absender (rein): unsere Versand- und Antwort-Domain oder eine eigene Weiterleitung. */
export function istSchleife(from: string | null, headers: Record<string, string> | null | undefined, env: Record<string, string | undefined> = process.env): boolean {
  if (Object.keys(headers ?? {}).some((k) => k.toLowerCase() === EINGANG_KOPF.toLowerCase())) return true;
  if (!from) return false;
  const domain = from.split("@")[1] ?? "";
  const eigene = [ANTWORT_DOMAIN, (leadMailAdresse(env) ?? "").split("@")[1] ?? ""].filter(Boolean);
  return eigene.some((d) => domain === d || domain.endsWith(`.${d}`));
}

