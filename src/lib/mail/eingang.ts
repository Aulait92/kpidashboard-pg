// Antworten an die Antwortadresse (Ole, 18.11.2026, Paket M2, docs/plan-mail-vorlagen.md): Resend Receiving meldet
// jede Mail an *@antwort.dein-beratungstermin.de als Webhook „email.received“ (app/api/resend/webhook). Der Webhook
// enthält keinen Inhalt; Text, Kopfzeilen, SPF/DKIM/DMARC und Anhänge kommen über die API (lib/mail/eingang-api.ts).
//
//   Zuordnung   1. Leadcode aus der Adresse (Lead.antwortCode), 2. Absenderadresse → Lead des Kunden (Kurzname,
//               auch frühere Kurznamen), 3. nur Kunde über den Kurznamen. Ohne Treffer: ignoriert.
//   Lead        Eintrag im Kontaktverlauf (ContactMail richtung „eingang“, Art „antwort“), Push an den zuständigen
//               Berater bzw. alle Logins („Neue Antwort von {Lead}“, ohne Inhalt), eigene Weiterleitung an den
//               Vermittler: von termine@… als „{Lead} (Antwort)“, Reply-To = Lead, Betreff „Antwort von {Lead}: …“,
//               Text und Anhänge (nicht receiving.forward: das setzt kein Reply-To). Zählt für die Stopp-Regeln
//               (hatMailAntwort in lead-sequences.ts und mail/sperren.ts).
//   Nur Kunde   Weiterleitung mit Hinweis „keinem Kontakt zugeordnet“, ohne Anhänge, kein Verlauf, kein Push,
//               höchstens 20 je Kunde und Tag.
//   Schutz      Automatische Antworten (Auto-Submitted, Precedence, Abwesenheitsnotiz, Listen, Unzustellbar) und
//               Absender mit SPF/DKIM/DMARC-Fehler: nur Hinweis im Verlauf, keine Weiterleitung, kein Stopp.
//               Eigene Absender und unsere Weiterleitungen (X-PG-Eingang) werden ignoriert (Schleifenschutz).
//               Ausführbare Dateien, Archive und Makro-Dokumente werden nie weitergeleitet und nicht zum Download
//               angeboten. Anhänge werden nie per KI ausgewertet (Gesundheitsangaben möglich).
//   Schalter    MAIL_ANTWORT_EINGANG aus: Eingänge mit gültigem Leadcode (Adresse wurde vergeben) werden trotzdem
//               verarbeitet, damit keine Antwort verloren geht; alles andere wird ignoriert.
//   Idempotenz  MailEingang je Resend-ID mit Fortschritt (Verlauf, Weiterleitung, Push); Wiederholungen des Webhooks
//               setzen dort fort. Keine Inhalte in Logs oder Sentry, nur Kurzgründe.

