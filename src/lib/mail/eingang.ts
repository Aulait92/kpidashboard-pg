const FERTIG = new Set(["antwort", "hinweis", "ignoriert"]);
const istEindeutigFehler = (e: unknown) => !!e && typeof e === "object" && (e as { code?: string }).code === "P2002";

/** Eintrag je Resend-ID anlegen bzw. für eine Wiederholung übernehmen; null = schon erledigt bzw. gerade in Arbeit. */
async function reserviere(resendEmailId: string, now: Date): Promise<Zeile | null> {
  const sel = { id: true, contactMailId: true, weitergeleitetAt: true, pushAt: true, versuche: true } as const;
  try {
    return await prisma.mailEingang.create({ data: { resendEmailId, ergebnis: "in_arbeit", versuche: 1, createdAt: now }, select: sel });
  } catch (e) {
    if (!istEindeutigFehler(e)) throw e;
  }
  const alt = await prisma.mailEingang.findUnique({ where: { resendEmailId }, select: { ...sel, ergebnis: true, updatedAt: true } });
  if (!alt || FERTIG.has(alt.ergebnis) || alt.versuche >= 5) return null;
  if (alt.ergebnis === "in_arbeit" && alt.updatedAt.getTime() > now.getTime() - 10 * 60_000) return null;
  const r = await prisma.mailEingang.updateMany({ where: { id: alt.id, updatedAt: alt.updatedAt }, data: { ergebnis: "in_arbeit", versuche: { increment: 1 } } });
  return r.count ? { ...alt, versuche: alt.versuche + 1 } : null;
}

async function abschliessen(id: string, data: { ergebnis: string; grund?: string | null; customerId?: string | null; leadId?: string | null; zuordnung?: string }) {
  await prisma.mailEingang.update({ where: { id }, data: { ...data, grund: data.grund?.slice(0, 80) ?? null } });
}

/** Ziel der Weiterleitung: zuständiger Berater bzw. Beraterdresse bzw. Inhaber (wie Reply-To ohne Antwortadresse). */
export async function weiterleitungsZiel(customerId: string, leadId: string | null): Promise<{ email: string; userId: string | null } | null> {
  const [lead, customer, owners] = await Promise.all([
    leadId ? prisma.lead.findUnique({ where: { id: leadId }, select: { assignedUser: { select: { id: true, email: true, teamRole: true, customerId: true } } } }) : null,
    prisma.customer.findUnique({ where: { id: customerId }, select: { agentConfig: { select: { advisorEmail: true } } } }),
    prisma.user.findMany({ where: { customerId, role: "BUYER", teamRole: "owner" }, orderBy: { createdAt: "asc" }, select: { email: true } }),
  ]);
  const zustaendig = lead?.assignedUser && lead.assignedUser.customerId === customerId ? lead.assignedUser : null;
  const email = vermittlerAdresse({ zustaendig, advisorEmail: customer?.agentConfig?.advisorEmail, ersterInhaber: owners[0]?.email });
  if (!email) return null;
  return { email, userId: zustaendig?.id ?? null };
}

